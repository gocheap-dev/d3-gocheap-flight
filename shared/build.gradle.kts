/**
 * The per-environment values this build is pointed at — the four backend hosts, plus the privacy
 * page and support inbox the Profile tab leaves for — read out of local.properties, which is
 * git-ignored, so that moving a checkout between environments is a local change rather than a
 * committed one.
 *
 * Defaulted rather than required, for the same reason the application id is: a fresh clone has no
 * local.properties to read, and the defaults below are what each value has always held.
 *
 * Generated into `commonMain` rather than read through a `BuildConfig`, because every caller is
 * common code — see `Constants`, the four HTTP clients and `ProfileScreen`. That also means the
 * iOS framework, which Gradle compiles from this same module, is built against whatever is
 * configured here; the two platforms cannot drift apart over it.
 */
val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use(::load)
}

fun localPropertyOrNull(name: String): String? =
    (localProperties.getProperty(name) ?: System.getenv(name))?.takeIf(String::isNotBlank)

fun localProperty(name: String, default: String): String = localPropertyOrNull(name) ?: default

/**
 * What gets written into the generated file: one object per group, each a name-to-value map. A
 * key that is absent or blank falls back to the default, which is what it held as a literal
 * before.
 */
val buildValues = mapOf(
    // Read directly by the four HTTP clients and the three deeplink builders.
    "BaseUrls" to listOf(
        Triple("Hotel", "HOTEL_BASE_URL", "https://staging.hotel.lascade.com/"),
        Triple("Car", "CAR_BASE_URL", "https://staging.car.lascade.com/"),
        Triple("Flight", "FLIGHT_BASE_URL", "https://staging.plane.lascade.com/"),
        Triple("User", "USER_BASE_URL", "https://staging.data.lascade.com/api/v1/"),
    ),
    // Read through `Constants.Support`, which is where the Profile tab looks.
    "SupportLinks" to listOf(
        Triple("PrivacyPolicyUrl", "PRIVACY_POLICY_URL", "https://www.gocheap.xyz/privacy-policy"),
        Triple("Email", "SUPPORT_EMAIL", "support@lascade.com"),
    ),
).mapValues { (_, entries) ->
    entries.associate { (name, key, default) -> name to localProperty(key, default) }
}

val generateBuildValues by tasks.registering {
    val groups = buildValues
    val outputDir = layout.buildDirectory.dir("generated/buildValues/commonMain/kotlin")
    // So a changed value in local.properties re-runs this rather than being served from the cache.
    inputs.property("buildValues", groups)
    outputs.dir(outputDir)
    doLast {
        val packageDir = outputDir.get().asFile.resolve("com/gocheap/travel/utils")
        packageDir.mkdirs()
        packageDir.resolve("BuildValues.kt").writeText(
            buildString {
                appendLine("// Generated by the `generateBuildValues` task. Do not edit.")
                appendLine("package com.gocheap.travel.utils")
                groups.forEach { (group, values) ->
                    appendLine()
                    appendLine("internal object $group {")
                    values.forEach { (name, value) ->
                        val escaped = value.replace("\\", "\\\\").replace("\"", "\\\"")
                        appendLine("    const val $name = \"$escaped\"")
                    }
                    appendLine("}")
                }
            }
        )
    }
}

/**
 * The iOS half of what `androidApp` does with this same file: there local.properties becomes
 * BuildConfig fields, here it becomes `iosApp/Configuration/Secrets.xcconfig`, which
 * `Config.xcconfig` includes last — so every name written below overrides the blank committed
 * there. From the xcconfig the values reach Swift through Info.plist; see
 * `FirebaseBootstrap.Credentials` and `TravelSdkFlights`.
 *
 * Generated rather than hand-written so that local.properties is the single place a credential is
 * set for either platform, and the generated file stays git-ignored exactly as local.properties is.
 *
 * The Firebase entries deliberately do not fall back to the Android keys. A Firebase project holds
 * one app per platform, and the app id and the API key differ between them — pointing the iOS app
 * at `FIREBASE_APP_ID` would file its events under the Android app, with nothing on screen to say
 * so. Only the project and sender ids, which belong to the project rather than to one of its apps,
 * are shared. The Travelpayouts credentials are shared for the opposite reason: there is one
 * affiliate account, and the marker is what its revenue is paid against.
 */
val iosSecrets = mapOf(
    // Name in Secrets.xcconfig to the local.properties keys it is read from, in fallback order.
    "TEAM_ID" to listOf("IOS_TEAM_ID"),
    "TRAVELPAYOUTS_MARKER" to listOf("TRAVELPAYOUTS_MARKER"),
    "TRAVELPAYOUTS_API_KEY" to listOf("TRAVELPAYOUTS_API_KEY"),
    "TRAVELPAYOUTS_CLIENT_DEVICE_HOST" to listOf("TRAVELPAYOUTS_CLIENT_DEVICE_HOST"),
    "TRAVELPAYOUTS_APPSTORE_ID" to listOf("TRAVELPAYOUTS_APPSTORE_ID"),
    "FIREBASE_APP_ID" to listOf("IOS_FIREBASE_APP_ID"),
    "FIREBASE_API_KEY" to listOf("IOS_FIREBASE_API_KEY"),
    "FIREBASE_GCM_SENDER_ID" to listOf("IOS_FIREBASE_GCM_SENDER_ID", "FIREBASE_GCM_SENDER_ID"),
    "FIREBASE_PROJECT_ID" to listOf("IOS_FIREBASE_PROJECT_ID", "FIREBASE_PROJECT_ID"),
).mapValues { (_, keys) -> keys.firstNotNullOfOrNull { localPropertyOrNull(it) }.orEmpty() }

val generateIosSecrets by tasks.registering {
    group = "build setup"
    description = "Writes iosApp/Configuration/Secrets.xcconfig from local.properties."

    val values = iosSecrets
    val outputFile =
        rootProject.layout.projectDirectory.file("iosApp/Configuration/Secrets.xcconfig")
    // So a changed value in local.properties re-runs this rather than being served from the cache.
    inputs.property("iosSecrets", values)
    outputs.file(outputFile)

    doLast {
        val (set, unset) = values.entries.partition { it.value.isNotEmpty() }
        // `//` opens a comment in an xcconfig and would truncate the value silently, which for a
        // credential means a build that looks configured and is not. None of these should ever
        // hold one, so fail rather than write half a value out.
        set.forEach { (name, value) ->
            require(!value.contains("//")) {
                "$name contains `//`, which an xcconfig reads as the start of a comment."
            }
        }

        // A name that is unset is left out entirely rather than written blank: an include whose
        // only effect is to erase the value it overrides is a confusing way to say nothing.
        val contents = buildString {
            appendLine("// Generated by the `generateIosSecrets` Gradle task from local.properties.")
            appendLine("// Do not edit, and do not commit — see .gitignore.")
            appendLine("//")
            appendLine("// Config.xcconfig includes this last, so each name here wins over the blank")
            appendLine("// committed there. Names absent below keep whatever Config.xcconfig sets.")
            if (unset.isNotEmpty()) {
                appendLine("//")
                appendLine("// Unset in local.properties: " + unset.joinToString { it.key })
            }
            appendLine()
            set.forEach { (name, value) -> appendLine("$name=$value") }
        }

        val file = outputFile.asFile
        val previous = if (file.exists()) file.readText() else null
        if (contents == previous) return@doLast
        file.parentFile.mkdirs()
        file.writeText(contents)
        // Xcode resolves an xcconfig when the build starts, which is before this task runs as part
        // of that same build — so a value that changed in local.properties reaches the app one
        // build later. Phrased as `warning:` because that is what Xcode surfaces in its log.
        if (previous != null) {
            logger.warn(
                "warning: Secrets.xcconfig regenerated from local.properties — build again " +
                    "for the new values to reach the app."
            )
        }
    }
}

// So that building from Xcode keeps the file in step rather than it depending on anyone
// remembering: the project's "Compile Kotlin Framework" phase runs exactly this task, and it is
// the only Gradle invocation an iOS build makes.
tasks.matching { it.name.startsWith("embedAndSignAppleFrameworkForXcode") }
    .configureEach { dependsOn(generateIosSecrets) }


