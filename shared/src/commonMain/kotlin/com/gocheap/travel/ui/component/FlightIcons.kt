    /** Outline counterpart to [icon]: the path is stroked at a hairline weight, not filled. */
    private fun strokeIcon(
        name: String,
        pathData: String,
        strokeWidth: Float = 1.6f,
        autoMirrored: Boolean = false,
    ): ImageVector {
        return ImageVector.Builder(
            name = name,
            defaultWidth = 24.dp,
            defaultHeight = 24.dp,
            viewportWidth = 24f,
            viewportHeight = 24f,
            autoMirror = autoMirrored,
        ).apply {
            addPath(
                pathData = PathParser().parsePathString(pathData).toNodes(),
                fill = null,
                stroke = SolidColor(Color.Black),
                strokeLineWidth = strokeWidth,
                strokeLineCap = StrokeCap.Round,
                strokeLineJoin = StrokeJoin.Round,
            )
        }.build()
    }

    /**
     * [autoMirrored] flips the glyph when the layout runs right-to-left.
     *
     * Only for icons that point somewhere. A back arrow, a chevron into a page and a plane on a
     * route all mean "forward", and in Arabic or Hebrew forward is the other way; a clock or a
     * star means the same thing in both and would only look wrong reversed.
     */
    private fun icon(
        name: String,
        pathData: String,
        autoMirrored: Boolean = false,
    ): ImageVector {
        return ImageVector.Builder(
            name = name,
            defaultWidth = 24.dp,
            defaultHeight = 24.dp,
            viewportWidth = 24f,
            viewportHeight = 24f,
            autoMirror = autoMirrored,
        ).apply {
            addPath(
                pathData = PathParser().parsePathString(pathData).toNodes(),
                fill = SolidColor(Color.Black),
            )
        }.build()
    }
